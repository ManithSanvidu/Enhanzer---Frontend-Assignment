  readonly bills = signal<PurchaseBill[]>(this.initialBills);

  getBills() {
    return this.bills();
  }

  getBillById(id: number): PurchaseBill | undefined {
    return this.bills().find(b => b.id === id);
  }

  addBill(bill: PurchaseBill) {
    this.bills.update(prev => [...prev, bill]);
  }

  updateBill(id: number, updated: Partial<PurchaseBill>) {
    this.bills.update(prev => prev.map(b => b.id === id ? { ...b, ...updated } : b));
  }

  addItemToBill(billId: number, item: PurchaseBillItem) {
    this.bills.update(prev => prev.map(b => {
      if (b.id === billId) {
        const items = b.items ? [...b.items, item] : [item];
        const amount = items.reduce((sum, i) => sum + i.totalCost, 0);
        const due = amount - b.paid;
        return {
          ...b,
          items,
          amount,
          due: due > 0 ? due : 0
        };
      }
      return b;
    }));
  }
